#!/usr/bin/env node
/**
 * Vendors the Chinese faces of the Jack theme from Fontsource packages.
 *
 * The Noto SC variable fonts are split into ~100 unicode-range slices, so a page
 * only downloads the slices for the characters it shows. This script copies the
 * CJK slices into src/jack/theme/fonts/cjk/ and writes src/jack/theme/fonts-cjk.css.
 * Latin, Cyrillic and Vietnamese slices are skipped: the Instrument faces set
 * Latin text. Nothing is added to package.json, so upstream dependency files
 * stay untouched.
 *
 * Usage, from frontend/ (versions are recorded in the generated CSS):
 *   npm pack @fontsource-variable/noto-serif-sc@5.3.0 @fontsource-variable/noto-sans-sc@5.3.0
 *   # extract each .tgz, then:
 *   node jack/vendor-cjk-fonts.mjs <noto-serif-sc>/package <noto-sans-sc>/package
 */
import { copyFileSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs'
import { basename, dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const fontDir = join(root, 'src/jack/theme/fonts/cjk')
const cssFile = join(root, 'src/jack/theme/fonts-cjk.css')
const SKIPPED_SUBSETS = /-(latin|latin-ext|cyrillic|vietnamese)-wght-normal\.woff2$/

/**
 * Leaves emoji and pictographic symbols to the system font, so they keep their
 * colour glyphs instead of Noto's monochrome ones.
 * @param {string} range a `unicode-range` value
 */
function withoutEmoji(range) {
  return range
    .split(',')
    .map((token) => token.trim())
    .filter((token) => {
      const start = parseInt(token.replace(/^U\+/i, '').split('-')[0], 16)
      return !(start >= 0x1f000 || (start >= 0x2600 && start <= 0x27bf))
    })
    .join(',')
}

const packages = process.argv.slice(2)
if (packages.length === 0) {
  console.error('usage: node jack/vendor-cjk-fonts.mjs <fontsource package dir>...')
  process.exit(1)
}

rmSync(fontDir, { recursive: true, force: true })
mkdirSync(fontDir, { recursive: true })

const sections = []
for (const pkgDir of packages) {
  const pkg = JSON.parse(readFileSync(join(pkgDir, 'package.json'), 'utf8'))
  const css = readFileSync(join(pkgDir, 'wght.css'), 'utf8')
  const blocks = css.match(/@font-face\s*{[^}]*}/g) ?? []
  const kept = []
  for (const block of blocks) {
    const url = /url\(\.\/files\/([^)]+\.woff2)\)/.exec(block)
    const range = /unicode-range:\s*([^;]+);/.exec(block)
    if (!url || !range || SKIPPED_SUBSETS.test(url[1])) continue
    const cjkRange = withoutEmoji(range[1])
    if (!cjkRange) continue
    copyFileSync(join(pkgDir, 'files', url[1]), join(fontDir, url[1]))
    kept.push(
      block
        .replace(url[0], `url('@/jack/theme/fonts/cjk/${url[1]}')`)
        .replace(range[0], `unicode-range: ${cjkRange};`)
    )
  }
  const licence = `LICENSE-${basename(pkg.name)}.txt`
  copyFileSync(join(pkgDir, 'LICENSE'), join(fontDir, licence))
  sections.push(`/* ${pkg.name}@${pkg.version}: ${kept.length} slices, ${licence} */\n${kept.join('\n\n')}`)
}

writeFileSync(
  cssFile,
  `/*
 * Jack theme Chinese fonts: Noto Serif SC (titles) and Noto Sans SC (text).
 * Generated by frontend/jack/vendor-cjk-fonts.mjs; do not edit by hand.
 * SIL Open Font License 1.1 (licences in fonts/cjk/). Each @font-face covers one
 * unicode-range slice, so browsers only fetch the slices a page needs.
 */
${sections.join('\n\n')}
`
)

const files = readdirSync(fontDir).filter((file) => file.endsWith('.woff2'))
console.log(`[jack-theme] wrote ${files.length} font slices and ${cssFile}`)
